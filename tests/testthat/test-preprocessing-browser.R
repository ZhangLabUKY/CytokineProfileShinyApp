test_that("theme changes preserve wizard controls and uploads can be replaced without editing", {
  skip_on_cran()
  skip_if_appdriver_disabled()
  app <- shinytest2::AppDriver$new(appdriver_app_dir(), name = "replacement-upload",
                                  load_timeout = 30000, timeout = 30000)
  withr::defer(app$stop())
  appdriver_wait_for_input(app, "nav_start_home")
  app$click("nav_start_home")
  appdriver_wait_for_input(app, "datafile")
  first <- readxl::readxl_example("datasets.xlsx")
  second <- readxl::readxl_example("deaths.xlsx")
  app$upload_file(datafile = first)
  appdriver_wait_for_input(app, "sheet_name")
  app$wait_for_js(sprintf("document.querySelector('#sheet_name')?.value === %s",
                         encodeString(readxl::excel_sheets(first)[1], quote = '"')))
  app$set_inputs(sheet_name = "chickwts")
  app$run_js("void (window.uploadBeforeTheme = document.getElementById('datafile'))")
  app$set_inputs(theme_choice = "darkly")
  app$wait_for_js("getComputedStyle(document.body).backgroundColor === 'rgb(34, 34, 34)'")
  expect_true(app$get_js("document.getElementById('datafile') === window.uploadBeforeTheme"))
  expect_identical(app$get_value(input = "sheet_name"), "chickwts")
  app$click("next1")
  chickwts_sheet <- readxl::read_excel(first, sheet = "chickwts")
  appdriver_expect_filtered_rows(app, nrow(chickwts_sheet))
  app$set_inputs(selected_categorical_cols = "feed")
  app$click(selector = "#filter_accordion .accordion-button")
  appdriver_wait_for_input(app, "filter_feed")
  app$set_inputs(filter_feed = "horsebean")
  filtered_count <- sum(chickwts_sheet$feed == "horsebean")
  appdriver_expect_filtered_rows(app, filtered_count)
  app$run_js("void (window.filterBeforeTheme = document.getElementById('filter_feed'))")
  app$set_inputs(theme_choice = "flatly")
  app$wait_for_js("getComputedStyle(document.body).backgroundColor === 'rgb(255, 255, 255)'")
  expect_true(app$get_js("document.getElementById('filter_feed') === window.filterBeforeTheme"))
  expect_true(app$get_js("document.querySelector('#filter_accordion .accordion-button').getAttribute('aria-expanded') === 'true'"))
  expect_identical(app$get_value(input = "filter_feed"), "horsebean")
  appdriver_expect_filtered_rows(app, filtered_count)
  app$click("back2")
  appdriver_wait_for_input(app, "datafile")
  app$upload_file(datafile = second)
  app$wait_for_js(sprintf("document.querySelector('#sheet_name')?.selectize?.getValue() === %s",
                         encodeString(readxl::excel_sheets(second)[1], quote = '"')))
  # Selectize keeps all choices in its widget, while the underlying select may
  # contain only the selected value.
  expect_setequal(app$get_js("Object.keys(document.querySelector('#sheet_name').selectize.options)"),
                  readxl::excel_sheets(second))
  app$click("open_editor")
  appdriver_wait_for_input(app, "cancel_data_editor")
  app$click("cancel_data_editor")
  app$click("next1")
  appdriver_expect_filtered_rows(app, nrow(readxl::read_excel(second, sheet = 1)))
  app$click("back2")
  appdriver_wait_for_input(app, "datafile")
  app$upload_file(datafile = test_path("ExampleData1.csv"))
  app$click("open_editor")
  appdriver_wait_for_input(app, "bioplex_colname_4")
  app$set_inputs(bioplex_colname_4 = "EditedMarker")
  app$click("bioplex_apply_names_modal")
  appdriver_wait_for_input(app, "bioplex_confirm_modal")
  app$click("bioplex_confirm_modal")
  app$click("next1")
  appdriver_expect_filtered_rows(app, 297)
  app$wait_for_js("!!document.querySelector('#selected_numerical_cols input[value=\"EditedMarker\"]')")
})

test_that("transformation popup commits explicitly and missing-value treatment can be undone", {
  skip_on_cran()
  skip_if_appdriver_disabled()
  app <- shinytest2::AppDriver$new(appdriver_app_dir(), name = "preprocessing-controls",
                                  load_timeout = 30000, timeout = 30000)
  withr::defer(app$stop())
  appdriver_wait_for_input(app, "nav_start_home")
  app$click("nav_start_home")
  appdriver_wait_for_input(app, "use_builtin")
  app$set_inputs(use_builtin = TRUE)
  appdriver_wait_for_input(app, "built_in_choice")
  app$set_inputs(built_in_choice = "ExampleData2")
  app$click("next1")
  appdriver_expect_filtered_rows(app, 66)
  appdriver_apply_transform(app, "log2", "IL.10")
  expect_match(app$get_value(output = "transform_summary"), "log2: IL.10", fixed = TRUE)
  app$click("configure_transform")
  appdriver_wait_for_input(app, "step2_scale")
  app$set_inputs(step2_scale = "log10")
  appdriver_wait_for_input(app, "cancel_transform")
  app$click("cancel_transform")
  app$wait_for_js("!document.getElementById('step2_scale')")
  expect_match(app$get_value(output = "transform_summary"), "log2: IL.10", fixed = TRUE)
  app$click("open_impute_modal")
  app$wait_for_value(output = "imp_na_before")
  expect_match(app$get_value(output = "imp_na_before"), "3\\.00")
  expect_setequal(
    app$get_js("Array.from(document.querySelectorAll('#imp_cols input'), x => x.value)"),
    c("IFN.G", "IL.1B", "TNF.A")
  )
  app$click("apply_impute")
  app$wait_for_js("!document.getElementById('shiny-modal')")
  expect_false(app$get_js("!!document.getElementById('undo_impute')"))
  app$click("next2")
  appdriver_wait_for_input(app, "back3")
  app$click("back3")
  appdriver_wait_for_input(app, "open_impute_modal")
  app$click("open_impute_modal")
  appdriver_wait_for_input(app, "undo_impute")
  app$wait_for_js("window.jQuery('#undo_impute').is(':visible')")
  app$wait_for_value(output = "imp_na_after")
  expect_match(app$get_value(output = "imp_na_after"), "\\b0\\s+0\\b")
  app$set_inputs(imp_cols = "IFN.G")
  app$click("undo_impute")
  app$wait_for_js("!window.jQuery('#undo_impute').is(':visible')")
  expect_true(app$get_js("window.jQuery('#imp_cols').is(':visible')"))
  expect_identical(app$get_value(input = "imp_cols"), "IFN.G")
  expect_match(app$get_value(output = "imp_na_before"), "3\\.00")
  app$click("close_impute")
  app$wait_for_js("!document.getElementById('shiny-modal')")
  expect_match(app$get_value(output = "transform_summary"), "log2: IL.10", fixed = TRUE)
  appdriver_apply_transform(app, "none")
  expect_identical(app$get_value(output = "transform_summary"), "No transformation applied.")
})
